#!/usr/bin/env python3
"""Generate the metric AprilTag roof panel as native Gazebo visuals."""

from pathlib import Path

import cv2


def visual(name, x, y, z, size, color):
    return f'''      <visual name="{name}">
        <pose>{x:.6f} {y:.6f} {z:.6f} 0 0 0</pose>
        <geometry><box><size>{size} {size} 0.001</size></box></geometry>
        <cast_shadows>false</cast_shadows>
        <material><ambient>{color} {color} {color} 1</ambient>
          <diffuse>{color} {color} {color} 1</diffuse></material>
      </visual>'''


def main():
    dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)
    if hasattr(cv2.aruco, 'generateImageMarker'):
        cells = cv2.aruco.generateImageMarker(dictionary, 7, 8)
    else:
        cells = cv2.aruco.drawMarker(dictionary, 7, 8)
    visuals = [visual('quiet_margin', 0, 0, 0, 0.5, 1)]
    for row in range(8):
        for col in range(8):
            if cells[row, col] == 0:
                visuals.append(visual(f'cell_{row}_{col}', (col - 3.5) * 0.05,
                                      (3.5 - row) * 0.05, 0.001, 0.05, 0))
    text = '''<?xml version="1.0"?>
<!-- Generated by scripts/generate_fiducial_model.py: tag 7, 36h11, 0.4 m edge. -->
<sdf version="1.9">
  <model name="ugv_fiducial">
    <link name="fiducial_link">
      <inertial><mass>0.001</mass><inertia>
        <ixx>0.00001</ixx><iyy>0.00001</iyy><izz>0.00001</izz>
      </inertia></inertial>
''' + '\n'.join(visuals) + '''
    </link>
  </model>
</sdf>
'''
    target = Path(__file__).resolve().parents[1] / 'simulation/models/ugv_fiducial/model.sdf'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)


if __name__ == '__main__':
    main()
